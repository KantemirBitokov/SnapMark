    /// <summary>Поиск по ключевым словам (английским и русским); все слова запроса должны найтись.</summary>
    public static IEnumerable<Emoji> Search(string query)
    {
        var words = query.ToLowerInvariant().Split(' ', StringSplitOptions.RemoveEmptyEntries);
        if (words.Length == 0) yield break;
        var seen = new HashSet<string>();
        foreach (var c in Categories)
            foreach (var e in c.Items)
                if (words.All(w => e.Keywords.Contains(w, StringComparison.Ordinal) || e.Text.Contains(w)) && seen.Add(e.Text))
                    yield return e;
    }
